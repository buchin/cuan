export interface ParsedTaskReport {
  isReport: true
  status: ReportStatus
  title: string
  badgeText: string
  body: string
  dodDetails?: DoDReportDetails
}

/**
 * Parses structured Definition of Done (DoD) evaluation reports generated by
 * Scrum Master / Reviewer agent.
 */
function parseDoDReport(content: string, language: string = 'en'): ParsedTaskReport | null {
  if (!content) return null
  const trimmed = content.trim()

  const dodTitleRegex = /(?:^|\n)(?:###?\s*)?(?:Evaluasi\s+(?:Definition\s+of\s+Done|DoD|Kriteria\s+Selesai)|Definition\s+of\s+Done\s+\(DoD\)\s+Evaluation|DoD\s+Evaluation|Acceptance\s+Criteria\s+Evaluation)(?:\s*\([^\)]*\))?[:\s]*/i
  const titleMatch = trimmed.match(dodTitleRegex)
  if (!titleMatch) return null

  // Ensure this is truly a report header, not just a casual mention inside a sentence
  const prefix = trimmed.slice(0, titleMatch.index).trim()
  if (prefix.length > 50) return null

  const reportBlock = trimmed.slice(titleMatch.index! + titleMatch[0].length)

  // Status extraction
  let status: ReportStatus = 'info'
  let statusRaw = ''
  const statusMatch = reportBlock.match(/(?:^|\n)\s*(?:[-*]\s*)?(?:\*\*Status(?:\*\*)?\s*:|Status\s*:)(?:\*\*)?\s*([^\n]+)/i)
  if (statusMatch) {
    statusRaw = statusMatch[1].trim().replace(/^[\*\-\s]+|[\*\-\s]+$/g, '').trim()
    const cleanStatus = statusRaw.toLowerCase()
    if (/\b(?:terkendala|blocked|gagal|failed)\b/i.test(cleanStatus)) {
      status = 'blocked'
    } else if (/\b(?:belum|revisi|revision|review|tinjau|perlu)\b/i.test(cleanStatus)) {
      status = 'review'
    } else if (/\b(?:lulus|pass|passed|selesai|success|sukses)\b/i.test(cleanStatus)) {
      status = 'success'
    }
  }

  // Task Title
  let taskTitle: string | undefined
  const taskMatch = reportBlock.match(/(?:^|\n)\s*(?:[-*]\s*)?(?:\*\*Task(?:\*\*)?\s*:|Task\s*:)(?:\*\*)?\s*([^\n]+)/i)
  if (taskMatch) {
    taskTitle = taskMatch[1].trim().replace(/^[\*\-\s]+|[\*\-\s]+$/g, '').trim()
  }

  // Summary / Ringkasan
  let summary: string | undefined
  const summaryMatch = reportBlock.match(/(?:^|\n)\s*(?:[-*]\s*)?(?:\*\*Ringkasan(?:\*\*)?\s*:|Ringkasan\s*:|\*\*Summary(?:\*\*)?\s*:|Summary\s*:)(?:\*\*)?\s*([^\n]+(?:\n(?!\s*(?:[-*]|\*\*|###|[A-Z][a-zA-Z\s]+:))[^\n]+)*)/i)
  if (summaryMatch) {
    summary = summaryMatch[1].trim().replace(/^[\*\-\s]+|[\*\-\s]+$/g, '').trim()
  }

  const checklist: DoDItem[] = []
  const gaps: DoDItem[] = []
  let hasExplicitNoGap = false

  const parseItemLine = (line: string): DoDItem | null => {
    const checkMatch = line.match(/^[-*]\s*(?:\[([ xX])\])?\s*([A-Za-z0-9_\[\*\(].+)$/)
    if (!checkMatch) return null
    const isCompleted = checkMatch[1] ? checkMatch[1].toLowerCase() === 'x' : true
    const rawContent = checkMatch[2].trim()
    if (!rawContent || rawContent === '*' || rawContent === '**') return null

    // Match **Title**: Detail or Title: Detail
    const splitMatch = rawContent.match(/^(?:\*\*([^*]+)\*\*|([A-Za-z0-9\s/_-]+))\s*:\s*(.+)$/)
    if (splitMatch) {
      const title = (splitMatch[1] || splitMatch[2]).trim()
      const detail = splitMatch[3].trim().replace(/^\*+|\*+$/g, '').trim()
      return { text: rawContent, title, detail, completed: isCompleted }
    }
    return { text: rawContent, completed: isCompleted }
  }

  // Parse Checklist / Bukti yang Terverifikasi
  const sectionBoundary = `(?=(?:\\n\\s*(?:[-*]\\s*)?(?:###?\\s*)?(?:\\*\\*)?(?:Checklist\\s+DoD|Bukti\\s+yang\\s+Terverifikasi|Verified\\s+Evidence|Acceptance\\s+Checklist|Verifikasi\\s+Teknis|Technical\\s+Verification|Gap(?:\\/Tindak\\s+Lanjut)?|Belum\\s+Terbukti|Tindakan|Action|\\n\\n[A-Z]))|$)`

  const checklistSectionMatch = reportBlock.match(new RegExp(`(?:^|\\n)(?:[-*]\\s*)?(?:###?\\s*)?(?:\\*\\*)?(?:Checklist\\s+DoD|Bukti\\s+yang\\s+Terverifikasi|Verified\\s+Evidence|Acceptance\\s+Checklist)(?:\\*\\*)?\\s*:\\s*(?:\\*\\*)?\\n?([\\s\\S]*?)${sectionBoundary}`, 'i'))
  if (checklistSectionMatch) {
    const lines = checklistSectionMatch[1].split('\n')
    for (const line of lines) {
      const item = parseItemLine(line.trim())
      if (item) checklist.push(item)
    }
  }

  // Parse Gaps / Belum Terbukti
  const gapsSectionMatch = reportBlock.match(new RegExp(`(?:^|\\n)(?:[-*]\\s*)?(?:###?\\s*)?(?:\\*\\*)?(?:Gap(?:\\/Tindak\\s+Lanjut)?|Belum\\s+Terbukti(?:\\s*\\/\\s*Gap\\s+yang\\s+Perlu\\s+Diperbaiki)?|Gaps?|Unmet\\s+Criteria)(?:\\*\\*)?\\s*:\\s*(?:\\*\\*)?\\n?([\\s\\S]*?)${sectionBoundary}`, 'i'))
  if (gapsSectionMatch) {
    const rawGaps = gapsSectionMatch[1].trim()
    if (/\b(?:tidak\s+ada|none|seluruh\s+kriteria\s+terpenuhi|nihil|zero|0\s+gap)\b/i.test(rawGaps)) {
      hasExplicitNoGap = true
    } else {
      const lines = gapsSectionMatch[1].split('\n')
      for (const line of lines) {
        const item = parseItemLine(line.trim())
        if (item) {
          if (/\b(?:tidak\s+ada|none|seluruh\s+kriteria\s+terpenuhi|nihil)\b/i.test(item.text)) {
            hasExplicitNoGap = true
          } else {
            gaps.push(item)
          }
        }
      }
    }
  }

  // Parse Technical Verification
  let technicalVerification: DoDTechnicalVerification | undefined
  const techSectionMatch = reportBlock.match(new RegExp(`(?:^|\\n)(?:[-*]\\s*)?(?:###?\\s*)?(?:\\*\\*)?(?:Verifikasi\\s+Teknis|Technical\\s+Verification)(?:\\*\\*)?\\s*:\\s*(?:\\*\\*)?\\n?([\\s\\S]*?)${sectionBoundary}`, 'i'))
  if (techSectionMatch) {
    const techText = techSectionMatch[1]
    technicalVerification = { rawLines: [] }

    // Commit hash (extracts 7 to 40 characters)
    const commitMatch = techText.match(/(?:Commit|SHA)\s*:\s*([a-f0-9]{7,40})(?:\s*\(([^)]+)\))?/i)
    if (commitMatch) {
      technicalVerification.commit = commitMatch[1]
      technicalVerification.commitShort = commitMatch[1].slice(0, 7)
      if (commitMatch[2]) technicalVerification.branch = commitMatch[2].trim()
    }

    // Branch (if on separate line)
    const branchMatch = techText.match(/(?:[-*]\s*)?Branch\s*:\s*([^\s\n]+)/i)
    if (branchMatch && !technicalVerification.branch) {
      technicalVerification.branch = branchMatch[1].trim()
    }

    // Lint / Build
    const lintMatch = techText.match(/(?:[-*]\s*)?(?:Lint\/Build|Build\/Test|Build|Lint|Test)\s*:\s*([^\n]+)/i)
    if (lintMatch) {
      technicalVerification.lintBuild = lintMatch[1].trim()
    }

    // Deploy
    const deployMatch = techText.match(/(?:[-*]\s*)?(?:Deploy(?:ment)?)\s*:\s*([^\n]+)/i)
    if (deployMatch) {
      technicalVerification.deploy = deployMatch[1].trim()
    }

    const rawLines = techText.split('\n')
      .map(l => l.trim())
      .filter(l => l.startsWith('-') || l.startsWith('*'))
      .filter(l => !l.match(/^(?:[-*]\s*)?(?:Commit|Branch|Lint\/Build|Build|Lint|Deploy)/i))
      .map(l => l.replace(/^[-*]\s*/, ''))
    if (rawLines.length > 0) {
      technicalVerification.rawLines = rawLines
    }
  }

  // Action / Tindakan
  let action: string | undefined
  const actionMatch = reportBlock.match(/(?:^|\n)\s*(?:[-*]\s*)?(?:\*\*Tindakan(?:\*\*)?\s*:|Tindakan\s*:|\*\*Action(?:\*\*)?\s*:|Action\s*:)(?:\*\*)?\s*([^\n]+)/i)
  if (actionMatch) {
    action = actionMatch[1].trim().replace(/^[\*\-\s]+|[\*\-\s]+$/g, '').trim()
  }

  // Trailing text after report block (e.g. delegation confirmation)
  let remainingText: string | undefined
  const lastSectionRegex = /(?:Tindakan|Action)\s*:[^\n]+/i
  const lastSection = reportBlock.match(lastSectionRegex)
  if (lastSection) {
    const afterLast = reportBlock.slice(lastSection.index! + lastSection[0].length).trim()
    if (afterLast) {
      remainingText = afterLast
    }
  }

  const title = language === 'id' ? 'Evaluasi Definition of Done' : 'Definition of Done Evaluation'
  const badgeText = status === 'success'
    ? (language === 'id' ? 'Lulus' : 'Passed')
    : status === 'blocked'
      ? (language === 'id' ? 'Terkendala' : 'Blocked')
      : (language === 'id' ? 'Perlu Revisi' : 'Needs Revision')

  return {
    isReport: true,
    status,
    title,
    badgeText,
    body: reportBlock,
    dodDetails: {
      taskTitle,
      statusRaw,
      summary,
      checklist,
      gaps,
      hasExplicitNoGap,
      technicalVerification,
      action,
      remainingText,
    },
  }
}

/**
 * Parses message content to detect if it is a task verification report,
 * Definition of Done evaluation, status checkpoint, or work update.
 * Returns structured report data or null.
 */
export function parseTaskReportMessage(content: string, language: string = 'en'): ParsedTaskReport | null {
  if (!content || typeof content !== 'string') return null
  const trimmed = content.trim()

  // 1. Definition of Done evaluation report
  const dodReport = parseDoDReport(trimmed, language)
  if (dodReport) {
    return dodReport
  }

  // 2. Verification report prefix
  const verificationMatch = trimmed.match(
    /^(?:Based on the work session's verification report|Berdasarkan laporan verifikasi sesi kerja|Based on the verification report|Berdasarkan laporan verifikasi|Verification report|Laporan verifikasi)\s*:\s*\n*/i
  )
  if (verificationMatch) {
    const body = trimmed.slice(verificationMatch[0].length).trim()
    const isExplicitPass = /\b(?:semua kriteria penerimaan telah terpenuhi|all acceptance criteria (?:are|have been) met|all criteria met|verified complete)\b/i.test(body)
    const isFailed = !isExplicitPass && (
      /\b(?:gagal|failed|tidak terpenuhi|unmet|contradictory|blocker|terdapat error|ada error)\b/i.test(body) ||
      (/\berror\b/i.test(body) && !/\b(?:tanpa|no|zero|0|without)\s+errors?\b/i.test(body))
    )
    const isReview = !isExplicitPass && !isFailed && /\b(?:needs review|perlu ditinjau|gap:|revision required|revisi)\b/i.test(body)

    const status: ReportStatus = isFailed ? 'failed' : isReview ? 'review' : 'success'
    const title = language === 'id' ? 'Laporan Verifikasi' : 'Verification Report'
    const badgeText = isFailed
      ? (language === 'id' ? 'Gagal' : 'Failed')
      : isReview
        ? (language === 'id' ? 'Perlu Tinjauan' : 'Review')
        : (language === 'id' ? 'Berhasil' : 'Success')

    return { isReport: true, status, title, badgeText, body }
  }

  // 3. Work update checking prefix
  const workUpdateMatch = trimmed.match(
    /^(?:Memeriksa pembaruan pekerjaan terbaru|Pembaruan pekerjaan|Work update)\s*[\.:]?\s*\n*/i
  )
  if (workUpdateMatch) {
    const body = trimmed.slice(workUpdateMatch[0].length).trim()
    const title = language === 'id' ? 'Pembaruan Pekerjaan' : 'Work Update'
    const badgeText = language === 'id' ? 'Sedang Berjalan' : 'In Progress'
    return { isReport: true, status: 'running', title, badgeText, body }
  }

  // 4. Review required prefix
  const reviewMatch = trimmed.match(
    /^(?:The result still needs review|Hasil masih perlu ditinjau|Review required|Perlu ditinjau)\s*[\.:]?\s*\n*/i
  )
  if (reviewMatch) {
    const body = trimmed.slice(reviewMatch[0].length).trim()
    const title = language === 'id' ? 'Tinjauan Hasil' : 'Review Required'
    const badgeText = language === 'id' ? 'Perlu Tinjauan' : 'Needs Review'
    return { isReport: true, status: 'review', title, badgeText, body }
  }

  // 5. Validation failed / blocked prefix
  const failedMatch = trimmed.match(
    /^(?:The result review could not be validated|Laporan verifikasi tidak dapat divalidasi|Validation failed|Tugas tertahan)\s*[\.:]?\s*\n*/i
  )
  if (failedMatch) {
    const body = trimmed.slice(failedMatch[0].length).trim()
    const title = language === 'id' ? 'Verifikasi Tertahan' : 'Validation Blocked'
    const badgeText = language === 'id' ? 'Tertahan' : 'Blocked'
    return { isReport: true, status: 'blocked', title, badgeText, body }
  }

  // 6. Markdown task report header e.g. "### Task Report: Success" or "### Status Report"
  const headerMatch = trimmed.match(
    /^(?:###|##)\s*(?:Task Report|Status Report|Laporan Tugas|Laporan Status)(?:\s*[:\-]\s*([^\n]+))?\n([\s\S]*)$/i
  )
  if (headerMatch) {
    const explicitStatus = (headerMatch[1] || '').trim().toLowerCase()
    let status: ReportStatus = 'info'
    if (/success|selesai|done|passed|berhasil/i.test(explicitStatus)) status = 'success'
    else if (/failed|gagal|blocked|error|tertahan/i.test(explicitStatus)) status = 'blocked'
    else if (/review|tinjau/i.test(explicitStatus)) status = 'review'
    else if (/running|doing|progress|berjalan/i.test(explicitStatus)) status = 'running'

    const body = headerMatch[2].trim()
    const title = headerMatch[1]?.trim() || (language === 'id' ? 'Laporan Tugas' : 'Task Report')
    const badgeText = status === 'success'
      ? (language === 'id' ? 'Berhasil' : 'Success')
      : status === 'blocked'
        ? (language === 'id' ? 'Tertahan' : 'Blocked')
        : status === 'review'
          ? (language === 'id' ? 'Perlu Tinjauan' : 'Review')
          : (language === 'id' ? 'Sedang Berjalan' : 'In Progress')

    return { isReport: true, status, title, badgeText, body }
  }

  return null
}

export interface StatusReportCardProps extends Omit<React.HTMLAttributes<HTMLDivElement>, 'title'> {
  status?: ReportStatus
  title?: React.ReactNode
  badgeText?: string
  headerIcon?: React.ReactNode
  actions?: React.ReactNode
  timestamp?: string | React.ReactNode
  children?: React.ReactNode
  compact?: boolean
  report?: ParsedTaskReport
}

export const StatusReportCard = React.forwardRef<HTMLDivElement, StatusReportCardProps>(
  (
    {
      status = 'info',
      title,
      badgeText,
      headerIcon,
      actions,
      timestamp,
      children,
      compact = false,
      report,
      className,
      ...props
    },
    ref
  ) => {
    const activeStatus = report?.status || status
    const activeTitle = title || report?.title
    const activeBadgeText = badgeText || report?.badgeText
    const dod = report?.dodDetails
    const theme = getReportStatusTheme(activeStatus)

    const [copiedCommit, setCopiedCommit] = React.useState(false)

    let HeaderIcon = theme.Icon
    if (dod) {
      if (activeStatus === 'success') HeaderIcon = ShieldCheck
      else if (activeStatus === 'review') HeaderIcon = RotateCcw
      else if (activeStatus === 'blocked' || activeStatus === 'failed') HeaderIcon = AlertCircle
    }

    return (
      <div
        ref={ref}
        data-report-status={activeStatus}
        className={cn(
          "status-report-card relative w-full min-w-0 max-w-full rounded-xl border text-sm transition-colors overflow-hidden break-words shadow-xs",
          theme.accentBorder,
          theme.containerBg,
          theme.containerBorder,
          compact ? "p-2.5 sm:p-3" : "p-3 sm:p-4",
          className
        )}
        {...props}
      >
        {/* Header */}
        <div className="flex flex-wrap items-center justify-between gap-1.5 sm:gap-2 border-b border-border/40 pb-2 mb-2.5">
          <div className="flex items-center gap-1.5 sm:gap-2 min-w-0 max-w-full">
            {headerIcon || (
              <HeaderIcon
                className={cn(
                  "h-4 w-4 shrink-0",
                  theme.iconColor,
                  activeStatus === "running" && "animate-spin"
                )}
                aria-hidden="true"
              />
            )}
            <span className="font-semibold text-xs sm:text-sm text-foreground truncate">
              {activeTitle || theme.defaultTitle}
            </span>
          </div>

          <div className="flex items-center gap-1.5 shrink-0">
            <span
              className={cn(
                "inline-flex items-center gap-1 rounded-full border px-2 py-0.5 text-[10px] sm:text-[11px] font-semibold tracking-wide uppercase",
                theme.badgeClasses
              )}
            >
              {activeStatus === 'success' && <CheckCircle2 className="h-3 w-3" />}
              {activeStatus === 'review' && <Clock3 className="h-3 w-3" />}
              {(activeStatus === 'failed' || activeStatus === 'blocked') && <AlertCircle className="h-3 w-3" />}
              {activeBadgeText || theme.defaultBadge}
            </span>
            {timestamp && (
              <span className="text-[11px] text-muted-foreground tabular-nums">
                {timestamp}
              </span>
            )}
          </div>
        </div>

        {/* DoD Structured Content */}
        {dod ? (
          <div className="space-y-2 min-w-0 max-w-full text-foreground/90">
            {/* Task Title */}
            {dod.taskTitle && (
              <div className="flex items-center gap-1.5 text-xs text-foreground/90 font-medium py-0.5 min-w-0">
                <CheckSquare className="h-3.5 w-3.5 text-primary shrink-0" />
                <span className="truncate">{dod.taskTitle}</span>
              </div>
            )}

            {/* Summary / Ringkasan */}
            {dod.summary && (
              <div className="text-xs sm:text-sm text-foreground/90 leading-relaxed break-words space-y-1">
                <div className="text-[10px] sm:text-[11px] font-semibold text-muted-foreground uppercase tracking-wide flex items-center gap-1">
                  <FileText className="h-3 w-3 text-muted-foreground shrink-0" />
                  <span>Ringkasan</span>
                </div>
                <div>{dod.summary}</div>
              </div>
            )}

            {/* DoD Checklist Items */}
            {dod.checklist && dod.checklist.length > 0 && (
              <div className="space-y-1 pt-1.5 border-t border-border/30">
                <div className="text-[10px] sm:text-[11px] font-semibold text-muted-foreground uppercase tracking-wide flex items-center gap-1 mb-1">
                  <ListChecks className="h-3 w-3 text-primary shrink-0" />
                  <span>Kriteria Selesai (DoD)</span>
                </div>
                <div className="space-y-1">
                  {dod.checklist.map((item, idx) => (
                    <div
                      key={idx}
                      className="flex items-start gap-2 py-0.5 text-xs sm:text-sm transition-colors text-foreground leading-snug"
                    >
                      {item.completed ? (
                        <CheckCircle2 className="h-3.5 w-3.5 text-emerald-600 dark:text-emerald-400 shrink-0 mt-0.5" />
                      ) : (
                        <AlertCircle className="h-3.5 w-3.5 text-amber-500 shrink-0 mt-0.5" />
                      )}
                      <div className="min-w-0 flex-1 leading-snug break-words">
                        {item.title && (
                          <span className="font-semibold text-foreground mr-1.5">
                            {item.title}:
                          </span>
                        )}
                        <span className="text-foreground/90">{item.detail || item.text}</span>
                      </div>
                    </div>
                  ))}
                </div>
              </div>
            )}

            {/* Gap / Tindak Lanjut Items */}
            <div className="space-y-1 pt-1.5 border-t border-border/30">
              <div className="text-[10px] sm:text-[11px] font-semibold text-muted-foreground uppercase tracking-wide flex items-center gap-1 mb-1">
                <AlertTriangle className="h-3 w-3 text-amber-500 shrink-0" />
                <span>Gap / Tindak Lanjut</span>
              </div>
              {dod.hasExplicitNoGap || (dod.gaps.length === 0 && activeStatus === 'success') ? (
                <div className="flex items-center gap-1.5 py-0.5 text-xs text-emerald-600 dark:text-emerald-400">
                  <Check className="h-3.5 w-3.5 shrink-0" />
                  <span>Semua kriteria terpenuhi (tidak ada gap)</span>
                </div>
              ) : (
                <div className="space-y-1">
                  {dod.gaps.map((gap, idx) => (
                    <div
                      key={idx}
                      className="flex items-start gap-2 py-0.5 text-xs sm:text-sm text-amber-800 dark:text-amber-300"
                    >
                      <AlertCircle className="h-3.5 w-3.5 text-amber-500 shrink-0 mt-0.5" />
                      <div className="min-w-0 flex-1 leading-snug break-words">
                        {gap.title && <span className="font-semibold mr-1.5">{gap.title}:</span>}
                        <span>{gap.detail || gap.text}</span>
                      </div>
                    </div>
                  ))}
                </div>
              )}
            </div>

            {/* Technical Verification */}
            {dod.technicalVerification && (
              <div className="space-y-1 pt-1.5 border-t border-border/30">
                <div className="text-[10px] sm:text-[11px] font-semibold text-muted-foreground uppercase tracking-wide flex items-center gap-1 mb-1">
                  <Terminal className="h-3 w-3 text-primary shrink-0" />
                  <span>Verifikasi Teknis</span>
                </div>
                <div className="pt-0.5 text-xs space-y-1.5">
                  {dod.technicalVerification.commit && (
                    <div className="flex items-center gap-2 flex-wrap min-w-0">
                      <span className="text-muted-foreground flex items-center gap-1 shrink-0">
                        <GitCommit className="h-3.5 w-3.5 text-muted-foreground" />
                        <span>Commit:</span>
                      </span>
                      <button
                        type="button"
                        onClick={() => {
                          if (dod.technicalVerification?.commit) {
                            navigator.clipboard.writeText(dod.technicalVerification.commit)
                            setCopiedCommit(true)
                            setTimeout(() => setCopiedCommit(false), 2000)
                          }
                        }}
                        title="Klik untuk copy commit SHA"
                        className="inline-flex items-center gap-1 font-mono text-[11px] bg-muted/50 px-1.5 py-0.5 rounded border border-border/60 hover:bg-muted transition-colors cursor-pointer"
                      >
                        <span>{dod.technicalVerification.commitShort || dod.technicalVerification.commit.slice(0, 7)}</span>
                        {copiedCommit ? <Check className="h-3 w-3 text-emerald-500" /> : <Copy className="h-3 w-3 text-muted-foreground opacity-60" />}
                      </button>
                      {dod.technicalVerification.branch && (
                        <span className="text-muted-foreground flex items-center gap-1 shrink-0">
                          <GitBranch className="h-3.5 w-3.5 text-muted-foreground" />
                          <span className="font-mono text-[11px] text-foreground/80 truncate max-w-[150px] sm:max-w-[220px]" title={dod.technicalVerification.branch}>
                            {dod.technicalVerification.branch}
                          </span>
                        </span>
                      )}
                    </div>
                  )}
                  {dod.technicalVerification.lintBuild && (
                    <div className="flex items-start gap-1.5">
                      <CheckCircle2 className="h-3.5 w-3.5 text-emerald-500 shrink-0 mt-0.5" />
                      <span className="text-foreground/90 break-words">{dod.technicalVerification.lintBuild}</span>
                    </div>
                  )}
                  {dod.technicalVerification.deploy && (
                    <div className="flex items-start gap-1.5">
                      <Rocket className="h-3.5 w-3.5 text-sky-500 shrink-0 mt-0.5" />
                      <span className="text-foreground/90 break-words">{dod.technicalVerification.deploy}</span>
                    </div>
                  )}
                  {dod.technicalVerification.rawLines && dod.technicalVerification.rawLines.map((line, idx) => (
                    <div key={idx} className="text-muted-foreground text-[11px] break-words">
                      • {line}
                    </div>
                  ))}
                </div>
              </div>
            )}

            {/* Action */}
            {dod.action && (
              <div className="flex items-center gap-1.5 text-xs text-muted-foreground pt-1 border-t border-border/30">
                <ArrowRight className="h-3.5 w-3.5 text-primary shrink-0" />
                <span>
                  <strong className="text-foreground font-semibold">Tindakan:</strong> {dod.action}
                </span>
              </div>
            )}
          </div>
        ) : (
          /* Standard Content Body */
          <div className="min-w-0 max-w-full text-foreground/90 leading-relaxed break-words">
            {children || report?.body}
          </div>
        )}

        {/* Optional Actions */}
        {actions && (
          <div className="mt-3 pt-2.5 border-t border-border/40 flex flex-wrap items-center gap-2">
            {actions}
          </div>
        )}
      </div>
    )
  }
)
StatusReportCard.displayName = "StatusReportCard"
